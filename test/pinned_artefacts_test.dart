// Pins on committed artefacts that no build step checks; the web ones (title, sqlite3.wasm, 8-bit icons) are ANTfrastructure's check-web-artefacts.py.
@TestOn('vm')
library;

import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:omni_accelerant/src/db/sqlite3_storage.dart';

/// Repo root, found by walking up from this file until pubspec.yaml appears.
Directory _repoRoot() {
  Directory dir = File.fromUri(Platform.script).parent;
  if (!File('${dir.path}/pubspec.yaml').existsSync()) {
    dir = Directory.current;
  }
  while (!File('${dir.path}/pubspec.yaml').existsSync()) {
    final Directory parent = dir.parent;
    if (parent.path == dir.path) {
      fail('could not find the repo root (no pubspec.yaml on the way up)');
    }
    dir = parent;
  }
  return dir;
}

String _read(String relative) {
  final File file = File('${_repoRoot().path}/$relative');
  if (!file.existsSync()) fail('missing file: $relative');
  return file.readAsStringSync();
}

/// First capture group of [pattern] in [relative], or a failure naming both.
String _extract(String relative, RegExp pattern, String what) {
  final RegExpMatch? match = pattern.firstMatch(_read(relative));
  if (match == null) {
    fail(
      'could not find $what in $relative — the pin moved or the file was '
      'restructured, so this test can no longer check it. Fix the pattern, do '
      'not delete the test.',
    );
  }
  return match.group(1)!;
}

void main() {
  test(
    'the app bar, the tab title, index.html and the manifest name the same app',
    () {
      // onGenerateTitle overrides index.html's <title>, so a stale setting showed the old blog's name.
      final Map<String, dynamic> settings = jsonDecode(
        _read('assets/settings/app_settings.json'),
      ) as Map<String, dynamic>;
      final String title = _extract(
        'web/index.html',
        RegExp(r'<title>([^<]+)</title>'),
        'the <title>',
      );
      final Map<String, dynamic> manifest =
          jsonDecode(_read('web/manifest.json')) as Map<String, dynamic>;
      for (final String key in <String>[
        'appNameDe',
        'appNameEn',
        'appTitleDe',
        'appTitleEn',
      ]) {
        expect(settings[key], title, reason: 'app_settings.json $key');
      }
      expect(manifest['name'], title, reason: 'web/manifest.json name');
    },
  );

  group('flutter_rust_bridge version pins agree', () {
    // The Rust side's exact `=` pin is the source of truth.
    late final String rustPin = _extract(
      'third_party/OxidANT/Cargo.toml',
      RegExp(r'^flutter_rust_bridge\s*=\s*"=([\d.]+)"', multiLine: true),
      'the flutter_rust_bridge = "=x.y.z" workspace pin',
    );

    test('the committed bindings were generated by the pinned codegen', () {
      final String codegen = _extract(
        'lib/src/rust/frb_generated.dart',
        RegExp(r"String get codegenVersion => '([\d.]+)'"),
        'codegenVersion',
      );
      expect(
        codegen,
        rustPin,
        reason:
            'lib/src/rust/ was generated by flutter_rust_bridge_codegen '
            '$codegen but third_party/OxidANT/Cargo.toml pins the runtime to '
            '$rustPin. The web build fails with an empty "Uncaught" before '
            'pkg/oxidant.js loads. Regenerate BOTH sides together: '
            '`flutter_rust_bridge_codegen generate`.',
      );
    });

    test('the pubspec constraint admits the pinned version', () {
      final String constraint = _extract(
        'pubspec.yaml',
        RegExp(r'^\s+flutter_rust_bridge:\s*\^?([\d.]+)', multiLine: true),
        'the flutter_rust_bridge dependency constraint',
      );

      final List<int> floor = constraint
          .split('.')
          .map((String p) => int.parse(p))
          .toList();
      final List<int> pinned = rustPin
          .split('.')
          .map((String p) => int.parse(p))
          .toList();

      expect(
        floor[0],
        pinned[0],
        reason: 'major mismatch: pubspec ^$constraint vs Rust $rustPin',
      );
      // A floor below the pin resolves correctly only by luck of the lock.
      expect(
        floor[1],
        greaterThanOrEqualTo(pinned[1]),
        reason:
            'pubspec.yaml allows flutter_rust_bridge ^$constraint while the '
            'Rust runtime is pinned to $rustPin. Raise the caret floor to '
            '^$rustPin so a resolve cannot pick a Dart runtime older than the '
            'generated bindings expect.',
      );
    });
  });

  group('the app version is written once', () {
    test('msix_config.msix_version follows version:', () {
      final String version = _extract(
        'pubspec.yaml',
        RegExp(r'^version:\s*(\d+\.\d+\.\d+)\+\d+\s*$', multiLine: true),
        'version: x.y.z+n',
      );
      final String msix = _extract(
        'pubspec.yaml',
        RegExp(r'^\s+msix_version:\s*([\d.]+)\s*$', multiLine: true),
        'msix_config.msix_version',
      );
      // The Store wants the fourth MSIX field at 0, so it cannot carry the build number.
      expect(
        msix,
        '$version.0',
        reason:
            'pubspec.yaml says version $version but msix_version $msix; the '
            'MSIX would install as another release than the Linux packages. '
            'Bump both together.',
      );
    });
  });

  test('the browser database keeps its name and path', () {
    // Renaming either opens an empty database in every visitor's browser and orphans the old one.
    expect(omniIndexedDbName, 'kataglyphis_inference_engine');
    expect(omniSqliteDatabasePath, '/kataglyphis.db');
  });

  test('every element of the Rust capture travels in the Linux bundle', () {
    // The packaged app loads only its bundled plugins; check-bundle-gst-elements.sh proves this list there.
    final RegExpMatch? list = RegExp(r'GST_PIPELINE_ELEMENTS=\(([^)]*)\)')
        .firstMatch(_read('scripts/linux/lib/bundle-runtime.sh'));
    expect(
      list,
      isNotNull,
      reason: 'bundle-runtime.sh has no GST_PIPELINE_ELEMENTS',
    );
    final Set<String> bundled = list!
        .group(1)!
        .split(RegExp(r'\s+'))
        .where((String name) => name.isNotEmpty)
        .toSet();
    const String capture = 'third_party/OxidANT/crates/media/src/capture.rs';
    final String source = _read(capture);
    final Set<String> made = <String>{
      for (final RegExpMatch m in RegExp(
        r'ElementFactory::make\("([a-z0-9]+)"\)',
      ).allMatches(source))
        m.group(1)!,
      if (source.contains('AppSink::builder()')) 'appsink',
    };
    final String webcams = _extract(
      capture,
      RegExp(r'for name in \[([^\]]*)\]'),
      'the webcam source list',
    );
    // Windows-only sources: find() skips them on Linux.
    final Set<String> linuxWebcams = <String>{
      for (final RegExpMatch m in RegExp(r'"([a-z0-9]+)"').allMatches(webcams))
        m.group(1)!,
    }.difference(<String>{'mfvideosrc', 'ksvideosrc'});
    expect(
      made,
      hasLength(greaterThanOrEqualTo(3)),
      reason: '$capture names fewer elements than its pipeline has',
    );
    expect(linuxWebcams, isNotEmpty, reason: 'no Linux webcam source left');
    for (final String element in <String>{...made, ...linuxWebcams}) {
      expect(
        bundled,
        contains(element),
        reason:
            '$capture uses $element: add it to GST_PIPELINE_ELEMENTS and '
            'its plugin to GST_BUNDLED_PLUGIN_NAMES in '
            'scripts/linux/lib/bundle-runtime.sh',
      );
    }
  });
}
